#!/usr/bin/env node
/**
 * Turns .env.<APP_ENV> (or .env) into src/config/env.generated.ts.
 *
 *   APP_ENV=staging node scripts/gen-env.js
 *
 * Everything written here is bundled into the app and therefore PUBLIC.
 * Never put a service key, a private signing key or any backend secret in an
 * env file. The Supabase anon key is public by design.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const appEnv = process.env.APP_ENV || 'development';
const candidates = [`.env.${appEnv}`, '.env', '.env.example'];
const file = candidates.map(f => path.join(root, f)).find(f => fs.existsSync(f));

const values = {};
if (file) {
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#')) values[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const KEYS = [
  'API_BASE_URL',
  'AI_API_BASE_URL',
  'SUPABASE_URL',
  'SUPABASE_ANON_KEY',
  'WEB_BASE_URL',
  'USE_MOCK_BACKEND',
];
const out = {
  APP_ENV: appEnv,
  ...Object.fromEntries(KEYS.map(k => [k, process.env[k] ?? values[k] ?? ''])),
};

const target = path.join(root, 'src/config/env.generated.ts');
fs.writeFileSync(
  target,
  `// Generated by scripts/gen-env.js. Do not edit; do not commit.\n// Values are bundled into the app and are public.\nexport const GENERATED_ENV: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`env: ${appEnv} <- ${file ? path.basename(file) : '(no env file, empty values)'}`);
